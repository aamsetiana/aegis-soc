'use client'

import { useState } from 'react'
import { FileText, Download, CheckCircle, ShieldAlert, FileSpreadsheet, Loader2 } from 'lucide-react'
import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'

export function ReportGeneratorClient({
  incidents,
  iocs,
  userName,
  userRole,
}: {
  incidents: any[]
  iocs: any[]
  userName: string
  userRole: string
}) {
  const [isGeneratingPdf, setIsGeneratingPdf] = useState(false)
  const [isGeneratingCsv, setIsGeneratingCsv] = useState(false)
  const [reportType, setReportType] = useState<'EXECUTIVE' | 'IOC' | 'FULL'>('EXECUTIVE')

  // Generate Formal PDF Executive Report
  function handleExportPDF() {
    setIsGeneratingPdf(true)
    try {
      const doc = new jsPDF()

      // Header Banner
      doc.setFillColor(15, 17, 24)
      doc.rect(0, 0, 210, 38, 'F')

      // Red Accent Stripe
      doc.setFillColor(239, 68, 68)
      doc.rect(0, 38, 210, 2, 'F')

      // Title & Subtitle
      doc.setTextColor(255, 255, 255)
      doc.setFontSize(18)
      doc.setFont('helvetica', 'bold')
      doc.text('AEGISSOC — EXECUTIVE INCIDENT POSTURE REPORT', 14, 18)

      doc.setFontSize(9)
      doc.setFont('helvetica', 'normal')
      doc.setTextColor(156, 163, 175)
      doc.text(
        `NIST SP 800-61 Rev. 2 Standard Compliance • Generated by: ${userName} (${userRole})`,
        14,
        26
      )
      doc.text(`Generated at: ${new Date().toLocaleString('id-ID')}`, 14, 32)

      // Summary Cards Box
      doc.setTextColor(15, 23, 42)
      doc.setFontSize(12)
      doc.setFont('helvetica', 'bold')
      doc.text('1. Ringkasan Eksekutif Metrik Insiden', 14, 50)

      const criticalCount = incidents.filter((i) => i.severity === 'CRITICAL').length
      const highCount = incidents.filter((i) => i.severity === 'HIGH').length
      const closedCount = incidents.filter((i) => i.status === 'CLOSED').length

      autoTable(doc, {
        startY: 55,
        head: [['Total Kasus', 'Kritis (Critical)', 'Tinggi (High)', 'Diselesaikan (Closed)', 'Total Artefak IOC']],
        body: [[incidents.length, criticalCount, highCount, closedCount, iocs.length]],
        theme: 'grid',
        headStyles: { fillColor: [239, 68, 68], textColor: 255, fontStyle: 'bold' },
        styles: { halign: 'center', fontSize: 10 },
      })

      // Incidents Table
      const currentY = (doc as any).lastAutoTable.finalY + 14
      doc.setFontSize(12)
      doc.setFont('helvetica', 'bold')
      doc.text('2. Rekapitulasi Kasus Insiden Terdaftar', 14, currentY)

      const incidentRows = incidents.map((inc) => [
        inc.caseNumber,
        inc.title,
        inc.category,
        inc.severity,
        `TLP:${inc.tlp}`,
        inc.status,
        new Date(inc.createdAt).toLocaleDateString('id-ID'),
      ])

      autoTable(doc, {
        startY: currentY + 5,
        head: [['Case #', 'Judul Kasus', 'Kategori', 'Severity', 'TLP', 'Status', 'Tanggal']],
        body: incidentRows,
        theme: 'striped',
        headStyles: { fillColor: [30, 41, 59], textColor: 255 },
        styles: { fontSize: 8 },
      })

      // IOC Table if requested
      if (reportType === 'IOC' || reportType === 'FULL') {
        doc.addPage()
        doc.setFontSize(12)
        doc.setFont('helvetica', 'bold')
        doc.text('3. Indikator Ancaman (IOC Threat Intel Feed)', 14, 20)

        const iocRows = iocs.map((ioc) => [
          ioc.type,
          ioc.value,
          ioc.threatLevel,
          ioc.case?.caseNumber || 'N/A',
          ioc.notes || '-',
        ])

        autoTable(doc, {
          startY: 25,
          head: [['Tipe IOC', 'Nilai Indikator (Value)', 'Threat Level', 'Kasus Asal', 'Catatan']],
          body: iocRows,
          theme: 'striped',
          headStyles: { fillColor: [239, 68, 68], textColor: 255 },
          styles: { fontSize: 8 },
        })
      }

      // Save PDF
      doc.save(`AegisSOC_Executive_Report_${Date.now()}.pdf`)
    } finally {
      setIsGeneratingPdf(false)
    }
  }

  // Export IOC Feed as CSV
  function handleExportIOC_CSV() {
    setIsGeneratingCsv(true)
    try {
      const headers = ['IOC_Type', 'Value', 'Threat_Level', 'Case_Number', 'Case_Title', 'Created_At']
      const rows = iocs.map((ioc) => [
        ioc.type,
        `"${ioc.value.replace(/"/g, '""')}"`,
        ioc.threatLevel,
        ioc.case?.caseNumber || '',
        `"${(ioc.case?.title || '').replace(/"/g, '""')}"`,
        ioc.createdAt,
      ])

      const csvContent =
        'data:text/csv;charset=utf-8,' +
        [headers.join(','), ...rows.map((e) => e.join(','))].join('\n')

      const encodedUri = encodeURI(csvContent)
      const link = document.createElement('a')
      link.setAttribute('href', encodedUri)
      link.setAttribute('download', `AegisSOC_IOC_Feed_${Date.now()}.csv`)
      document.body.appendChild(link)
      link.click()
      document.body.removeChild(link)
    } finally {
      setIsGeneratingCsv(false)
    }
  }

  // Export Incidents as CSV
  function handleExportIncidents_CSV() {
    setIsGeneratingCsv(true)
    try {
      const headers = [
        'Case_Number',
        'Title',
        'Category',
        'Severity',
        'TLP',
        'Status',
        'Reported_By',
        'Detected_At',
        'Created_At',
      ]
      const rows = incidents.map((inc) => [
        inc.caseNumber,
        `"${inc.title.replace(/"/g, '""')}"`,
        inc.category,
        inc.severity,
        inc.tlp,
        inc.status,
        `"${(inc.reportedBy?.name || '').replace(/"/g, '""')}"`,
        inc.detectedAt,
        inc.createdAt,
      ])

      const csvContent =
        'data:text/csv;charset=utf-8,' +
        [headers.join(','), ...rows.map((e) => e.join(','))].join('\n')

      const encodedUri = encodeURI(csvContent)
      const link = document.createElement('a')
      link.setAttribute('href', encodedUri)
      link.setAttribute('download', `AegisSOC_Incidents_Rekap_${Date.now()}.csv`)
      document.body.appendChild(link)
      link.click()
      document.body.removeChild(link)
    } finally {
      setIsGeneratingCsv(false)
    }
  }

  return (
    <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
      {/* PDF Export Card */}
      <div className="bg-[#11131a] border border-white/[0.06] rounded-2xl p-6 flex flex-col justify-between">
        <div>
          <div className="w-12 h-12 rounded-2xl bg-red-500/10 border border-red-500/30 flex items-center justify-center text-red-400 mb-4">
            <FileText className="w-6 h-6" />
          </div>

          <h3 className="text-lg font-bold text-white mb-1">
            Ekspor Laporan Resmi Eksekutif (PDF)
          </h3>
          <p className="text-xs text-slate-400 mb-6 leading-relaxed">
            Menghasilkan dokumen PDF berformat resmi yang mencakup ringkasan metrik kepatuhan NIST,
            tabel rekapitulasi seluruh insiden terdaftar, dan katalog indikator ancaman. Dokumen ini
            siap dilampirkan pada laporan tugas besar EdLink Anda.
          </p>

          <div className="space-y-3 mb-6">
            <label className="text-xs font-semibold text-slate-300 block">Cakupan Dokumen:</label>
            <div className="grid grid-cols-3 gap-2">
              {[
                { id: 'EXECUTIVE', label: 'Ringkasan Kasus' },
                { id: 'IOC', label: 'Kasus + IOC Feed' },
                { id: 'FULL', label: 'Full Dossier Report' },
              ].map((opt) => (
                <button
                  key={opt.id}
                  type="button"
                  onClick={() => setReportType(opt.id as any)}
                  className={`p-2.5 rounded-xl text-xs font-medium border text-center transition-all cursor-pointer ${
                    reportType === opt.id
                      ? 'bg-red-500/20 border-red-500/40 text-red-400'
                      : 'border-white/[0.06] bg-white/[0.02] text-slate-400 hover:text-white'
                  }`}
                >
                  {opt.label}
                </button>
              ))}
            </div>
          </div>
        </div>

        <button
          onClick={handleExportPDF}
          disabled={isGeneratingPdf}
          className="w-full py-3 rounded-xl bg-gradient-to-r from-red-600 to-orange-600 hover:from-red-500 hover:to-orange-500 text-white text-xs font-semibold shadow-lg shadow-red-600/25 transition-all flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
        >
          {isGeneratingPdf ? (
            <>
              <Loader2 className="w-4 h-4 animate-spin" /> Menghasilkan PDF...
            </>
          ) : (
            <>
              <Download className="w-4 h-4" /> Unduh Dokumen PDF Resmi
            </>
          )}
        </button>
      </div>

      {/* CSV Export Card */}
      <div className="bg-[#11131a] border border-white/[0.06] rounded-2xl p-6 flex flex-col justify-between">
        <div>
          <div className="w-12 h-12 rounded-2xl bg-emerald-500/10 border border-emerald-500/30 flex items-center justify-center text-emerald-400 mb-4">
            <FileSpreadsheet className="w-6 h-6" />
          </div>

          <h3 className="text-lg font-bold text-white mb-1">
            Ekspor Data Mentah Spreadsheet (CSV)
          </h3>
          <p className="text-xs text-slate-400 mb-6 leading-relaxed">
            Unduh berkas CSV terstruktur untuk keperluan analisis data lanjutan pada Microsoft
            Excel, Google Sheets, atau diimpor langsung ke perangkat perlindungan jaringan (Firewall
            Rules, SIEM, EDR Ingestion).
          </p>

          <div className="p-4 rounded-xl bg-black/40 border border-white/[0.06] text-xs space-y-2 mb-6">
            <div className="flex justify-between">
              <span className="text-slate-400">Total Baris Insiden:</span>
              <span className="font-mono text-white font-semibold">{incidents.length} baris</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-400">Total Baris Indikator IOC:</span>
              <span className="font-mono text-white font-semibold">{iocs.length} baris</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-400">Format Karakter:</span>
              <span className="font-mono text-emerald-400">UTF-8 Comma-Separated</span>
            </div>
          </div>
        </div>

        <div className="grid grid-cols-2 gap-3">
          <button
            onClick={handleExportIncidents_CSV}
            disabled={isGeneratingCsv}
            className="py-3 rounded-xl bg-white/[0.04] hover:bg-white/[0.08] border border-white/[0.08] text-white text-xs font-semibold transition-all flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
          >
            <Download className="w-4 h-4 text-emerald-400" /> Ekspor Insiden (CSV)
          </button>
          <button
            onClick={handleExportIOC_CSV}
            disabled={isGeneratingCsv}
            className="py-3 rounded-xl bg-white/[0.04] hover:bg-white/[0.08] border border-white/[0.08] text-white text-xs font-semibold transition-all flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
          >
            <Download className="w-4 h-4 text-orange-400" /> Ekspor IOC Feed (CSV)
          </button>
        </div>
      </div>
    </div>
  )
}
